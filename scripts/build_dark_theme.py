"""Generate site/assets/css/theme-dark.css from app.css.

The light theme is the main one. For the dark theme every rule in app.css that
paints a white surface or brand-coloured text gets a counterpart under
html[data-theme="dark"]: white surfaces become the dark surface colour, brand
text becomes light. Hand-written dark tweaks live in DARK_EXTRA below.
Re-run after editing app.css:  python3 scripts/build_dark_theme.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent / 'site' / 'assets' / 'css'
SRC, OUT = ROOT / 'app.css', ROOT / 'theme-dark.css'
P = 'html[data-theme="dark"]'
SURFACE = '18, 26, 42'  # rgb of --surface in dark

WHITE = re.compile(r'#fff(?:fff)?\b', re.I)
LIGHT_A = re.compile(r'rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*(\.?\d*\.?\d+)\s*\)')
LIGHT_HEX = re.compile(r'#([0-9a-f]{6})\b', re.I)
CANVAS = '11, 18, 32'  # rgb of --canvas in dark
WHITE_A = re.compile(r'rgba\(\s*255,\s*255,\s*255,\s*(\.?\d*\.?\d+)\s*\)')


def dark_value(prop, val):
    """Return the dark replacement for one declaration, or None to skip it."""
    if prop in ('background', 'background-color'):
        if 'url(' in val:
            return None
        v = WHITE.sub('var(--surface)', val)
        v = WHITE_A.sub(lambda m: f'rgba({SURFACE}, {m.group(1)})' if float(m.group(1)) >= .45 else m.group(0), v)
        # near-white greys (canvas tints) become the dark canvas
        v = LIGHT_A.sub(lambda m: f'rgba({CANVAS}, {m.group(4)})' if min(map(int, m.group(1, 2, 3))) >= 230 else m.group(0), v)
        v = LIGHT_HEX.sub(lambda m: 'var(--canvas)' if min(int(m.group(1)[i:i + 2], 16) for i in (0, 2, 4)) >= 0xE6 else m.group(0), v)
        return v if v != val else None
    if prop == 'color':
        if re.fullmatch(r'var\(--brand-strong\)\s*(!important)?', val):
            return 'var(--ink)' + (' !important' if 'important' in val else '')
        if re.fullmatch(r'var\(--brand(-600)?\)\s*(!important)?', val):
            return 'var(--link)' + (' !important' if 'important' in val else '')
        return None
    if prop in ('border', 'border-color', 'border-top', 'border-bottom'):
        v = WHITE_A.sub(lambda m: 'rgba(255, 255, 255, .08)' if float(m.group(1)) >= .45 else m.group(0), val)
        v = WHITE.sub('rgba(255, 255, 255, .1)', v)
        return v if v != val else None
    return None


def split_decls(body):
    out, depth, cur = [], 0, ''
    for ch in body:
        if ch == '(':
            depth += 1
        elif ch == ')':
            depth -= 1
        if ch == ';' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [d.strip() for d in out if ':' in d]


def walk(css):
    """Yield (wrapper, selector, body) for plain rules; wrapper is an @media prelude or ''."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    stack = []
    while i < n:
        j = css.find('{', i)
        k = css.find('}', i)
        if j == -1 and k == -1:
            break
        if k != -1 and (j == -1 or k < j):
            if stack:
                stack.pop()
            i = k + 1
            continue
        head = css[i:j].strip()
        if head.startswith('@media') or head.startswith('@supports'):
            stack.append(head)
            i = j + 1
            continue
        if head.startswith('@'):  # keyframes, font-face: skip the whole block
            depth, p = 1, j + 1
            while depth and p < n:
                depth += {'{': 1, '}': -1}.get(css[p], 0); p += 1
            i = p
            continue
        end = css.find('}', j)
        yield (stack[-1] if stack else ''), head, css[j + 1:end]
        i = end + 1


def scope(selector):
    parts = []
    for s in selector.split(','):
        s = s.strip()
        if not s:
            continue
        s = re.sub(r'^(html|:root)\b', '', s).strip()
        parts.append(f'{P} {s}' if s else P)
    return ', '.join(parts)


def main():
    blocks = {}
    for wrap, sel, body in walk(SRC.read_text()):
        decls = []
        for d in split_decls(body):
            prop, val = d.split(':', 1)
            prop, val = prop.strip().lower(), val.strip()
            nv = dark_value(prop, val)
            if nv:
                decls.append(f'{prop}: {nv}')
        if decls:
            blocks.setdefault(wrap, []).append(f'{scope(sel)} {{ {"; ".join(decls)}; }}')
    out = ['/* Generated by scripts/build_dark_theme.py from app.css. Do not edit by hand: edit DARK_EXTRA in the script. */']
    for wrap, rules in blocks.items():
        if wrap:
            out.append(f'{wrap} {{\n  ' + '\n  '.join(rules) + '\n}')
        else:
            out.extend(rules)
    out.append(DARK_EXTRA.strip())
    OUT.write_text('\n'.join(out) + '\n')
    print(f'{OUT.name}: {sum(len(r) for r in blocks.values())} rules')


